-- ---------------------------------------------------------------------------
-- order_line_items (view)
--
-- Flattens an order into human-readable lines. Used by the admin notification
-- so the Telegram message can name the product, size and colour without the
-- workflow having to join three tables itself.
-- ---------------------------------------------------------------------------
CREATE VIEW public.order_line_items AS
SELECT
  oi.order_id,
  oi.quantity,
  oi.price_at_purchase,
  p.name AS product_name,
  v.size,
  v.color
FROM order_items oi
JOIN variants v ON v.id = oi.variant_id
JOIN products p ON p.id = v.product_id;

-- ---------------------------------------------------------------------------
-- product_embeddings (view)
--
-- Assembles the text that gets embedded into Qdrant, in the database rather
-- than in the workflow. Keeping it here means the embedding text is defined in
-- one place and can be inspected with a plain SELECT before re-indexing.
--
-- Colours are aggregated so a shopper asking for "something in navy" can match
-- a product whose description never mentions the colour.
-- ---------------------------------------------------------------------------
CREATE VIEW public.product_embeddings AS
SELECT
  p.id,
  p.name || '\n' || p.gender || '\n' || 'Colors: '
    || COALESCE(string_agg(DISTINCT v.color, ', '), 'n/a')
    || '\n' || p.rich_description AS embedding_text,
  p.gender
FROM products p
LEFT JOIN variants v ON v.product_id = p.id
GROUP BY p.id, p.name, p.gender, p.rich_description;
